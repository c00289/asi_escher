"""The provenance marks: who drew the file, when, and which files share its layout.

A ``.drawio`` file written by :func:`asi_escher.to_drawio` is the real draw.io
artefact; the PNG and SVG beside it are asi_escher's renderings of the same
layout, not draw.io exports.  So the draw.io file says so in an XML comment
and in a small grey note under the drawing, and the renderings carry a grey
footer line naming the draw.io file they share their layout with.  Every
mark is switched off with ``provenance=False`` on the call that writes it.
"""
from __future__ import annotations

import datetime as _dt
import re
from importlib.metadata import PackageNotFoundError, version


def package_version() -> str:
    try:
        return version("asi_escher")
    except PackageNotFoundError:  # running from a source tree without installation
        return "0.0.0"


def today() -> str:
    return _dt.date.today().isoformat()


def slug(title: str) -> str:
    """File-system-safe stem derived from a diagram title."""
    s = re.sub(r"[^a-z0-9]+", "_", title.lower()).strip("_")
    return s or "diagram"


def drawio_comment(name: str) -> str:
    """The XML comment written right after the ``<mxfile>`` opening."""
    return (f" Generated by asi_escher {package_version()} on {today()}: boxes and arrows placed by "
            f"escher's layout; the {name}.png and {name}.svg beside this file are escher's renderings "
            f"of this same layout, not draw.io exports; edit this file in draw.io or the VS Code "
            f"draw.io extension ")


def drawio_note(name: str) -> str:
    """The one-line text of the grey note cell under the drawing."""
    return (f"asi_escher {package_version()}, {today()}: layout by escher; {name}.png and {name}.svg "
            f"are escher's renderings of this layout, not draw.io exports; edit here in draw.io")


def footer(name: str) -> str:
    """The grey footer line of a PNG / SVG rendering."""
    return f"asi_escher {package_version()}, {today()}; layout shared with {name}.drawio"
